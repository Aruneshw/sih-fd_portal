import { ArrowLeft, Printer } from 'lucide-react';
import { Link, useParams, useSearchParams } from 'react-router-dom';
import { formatDate, formatDateTime } from '@/lib/dates';
import { ROLE_LABEL } from '@/domain/labels';
import { can } from '@/domain/permissions/can';
import { REPORTS } from '@/services/export/reportDefinitions';
import { useAppState, useRuntime, useToday, useUser } from '@/app/hooks';

/** FR-M11-4: print-friendly view → browser Print to PDF. */
export function ReportPrintPage() {
  const { reportId } = useParams();
  const [params] = useSearchParams();
  const state = useAppState();
  const today = useToday();
  const user = useUser();
  const rt = useRuntime();
  const def = REPORTS.find((r) => r.id === reportId && (!r.requires || can(user, r.requires).allowed));
  if (!def) return <p className="p-6 text-sm">Report not found. <Link to="/reports" className="text-navy-700 underline">Back to reports</Link></p>;
  const f = { from: params.get('from') ?? '', to: params.get('to') ?? '', status: params.get('status') ?? '' };
  const out = def.build(state, today, user, f);
  const status = def.statusOptions.find((o) => o.value === f.status)?.label;
  return (
    <div className="mx-auto max-w-6xl bg-white p-6 text-slate-900">
      <div className="no-print mb-4 flex gap-2">
        <Link to={`/reports?report=${def.id}`} className="inline-flex items-center gap-1 rounded-md border border-slate-300 px-3 py-1.5 text-sm"><ArrowLeft size={16} aria-hidden /> Back</Link>
        <button type="button" onClick={() => window.print()} className="inline-flex items-center gap-1 rounded-md bg-navy-700 px-3 py-1.5 text-sm text-white"><Printer size={16} aria-hidden /> Print / Save as PDF</button>
      </div>
      <header className="mb-4 border-b-2 border-navy-900 pb-3">
        <div className="flex flex-wrap items-baseline justify-between gap-2">
          <h1 className="text-xl font-semibold text-navy-900">{def.title}</h1>
          <span className="rounded border border-amber-600 px-2 py-0.5 text-xs font-semibold text-amber-700">Demonstration data</span>
        </div>
        <p className="mt-1 text-xs text-slate-600">
          AICTE SecureFDR (prototype) · {def.id} · Filters: {[status && `status ${status}`, f.from && `${def.dateLabel.toLowerCase()} from ${formatDate(f.from)}`, f.to && `to ${formatDate(f.to)}`].filter(Boolean).join(', ') || 'none'} ·
          Generated by {user.name} ({ROLE_LABEL[user.role]}) · {formatDateTime(rt.clock.now())} · {out.rows.length} rows
        </p>
      </header>
      <table className="w-full border-collapse text-left text-[11px]">
        <thead><tr>{out.headers.map((h) => <th key={h} className="border border-slate-300 bg-slate-100 px-2 py-1">{h}</th>)}</tr></thead>
        <tbody>{out.rows.map((r, i) => <tr key={i} className="print-break">{r.map((c, j) => <td key={j} className="border border-slate-300 px-2 py-1 align-top">{c}</td>)}</tr>)}</tbody>
      </table>
      <p className="mt-4 text-[10px] text-slate-500">All records are fictional demonstration data. Statuses are derived from recorded data and do not imply financial validity. Not affiliated with or endorsed by AICTE or any bank.</p>
    </div>
  );
}
